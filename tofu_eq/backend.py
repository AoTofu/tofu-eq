"""Manages the PipeWire filter-chain (a systemd user service) and pushes live parameters.

Every band is a `bq_raw` biquad whose coefficients are computed in Python and
written with `pw-cli set-param` (b0..a2), so every change - even switching the
filter type - is applied without a dropout. The generated config also embeds a
coefficient table for each common sample rate, so the EQ is correct at login
and after rate changes without the GUI running.
"""
import json
import math
import shutil
import subprocess

from PySide6.QtCore import QObject, QProcess, QTimer, Signal

from . import dsp
from .i18n import tr
from .model import CONFIG_DIR

CONF_FILE = CONFIG_DIR / "filter-chain.conf"
SERVICE = "tofu-eq-filter.service"
UNIT_FILE = CONFIG_DIR.parent / "systemd" / "user" / SERVICE
NODE_IN = "tofu_eq.input"
NODE_OUT = "tofu_eq.output"
RATES = [44100, 48000, 88200, 96000, 176400, 192000, 352800, 384000]


def slots_for(n):
    return max(8, math.ceil(n / 8) * 8)


def slot_coeffs(state, slots, rate):
    out = []
    for i in range(slots):
        b = state.bands[i] if i < len(state.bands) else None
        if b is None or not b.enabled or state.bypass:
            out.append(dsp.IDENTITY)
        else:
            out.append(dsp.coeffs(b.type, b.freq, b.gain, b.q, rate))
    return out


def preamp_mult(state):
    return 1.0 if state.bypass else 10.0 ** (state.preamp / 20.0)


def _f(v):
    return f"{v:.12g}"


def build_conf(state, slots):
    tables = {r: slot_coeffs(state, slots, r) for r in RATES}
    nodes = [f'          {{ type = builtin name = pre label = linear control = {{ "Mult" = {_f(preamp_mult(state))} }} }}']
    for i in range(slots):
        rows = " ".join(
            "{ rate = %d b0 = %s b1 = %s b2 = %s a0 = %s a1 = %s a2 = %s }" % ((r,) + tuple(_f(c) for c in tables[r][i]))
            for r in RATES
        )
        nodes.append(f"          {{ type = builtin name = s{i + 1} label = bq_raw config = {{ coefficients = [ {rows} ] }} }}")
    chain = ["pre"] + [f"s{i + 1}" for i in range(slots)]
    links = "\n".join(f'          {{ output = "{a}:Out" input = "{b}:In" }}' for a, b in zip(chain, chain[1:]))
    nodes_s = "\n".join(nodes)
    return f"""# Generated by Tofu EQ - manual edits will be overwritten by the GUI
context.spa-libs = {{
    audio.convert.* = audioconvert/libspa-audioconvert
    support.*       = support/libspa-support
}}
context.modules = [
  {{ name = libpipewire-module-rt args = {{ nice.level = -11 }} flags = [ ifexists nofail ] }}
  {{ name = libpipewire-module-protocol-native }}
  {{ name = libpipewire-module-client-node }}
  {{ name = libpipewire-module-adapter }}
  {{ name = libpipewire-module-filter-chain
    args = {{
      node.description = "Tofu EQ"
      media.name       = "Tofu EQ"
      filter.graph = {{
        nodes = [
{nodes_s}
        ]
        links = [
{links}
        ]
        inputs  = [ "pre:In" ]
        outputs = [ "{chain[-1]}:Out" ]
      }}
      audio.channels = 2
      audio.position = [ FL FR ]
      capture.props = {{
        node.name         = "{NODE_IN}"
        media.class       = Audio/Sink
        filter.smart      = true
        filter.smart.name = "tofu-eq"
      }}
      playback.props = {{
        node.name    = "{NODE_OUT}"
        node.passive = true
      }}
    }}
  }}
]
"""


def build_unit():
    pw = shutil.which("pipewire") or "/usr/bin/pipewire"
    return f"""[Unit]
Description=Tofu EQ (PipeWire filter-chain)
After=pipewire.service
BindsTo=pipewire.service

[Service]
ExecStart={pw} -c "{CONF_FILE}"
Restart=on-failure
RestartSec=1

[Install]
WantedBy=pipewire.service
"""


def _systemctl(*args):
    return subprocess.run(["systemctl", "--user", *args], capture_output=True, text=True)


class Backend(QObject):
    rateChanged = Signal(int)
    deviceChanged = Signal(str)  # node.name of the real device the EQ outputs to
    status = Signal(str)

    def __init__(self, parent=None):
        super().__init__(parent)
        self.rate = 48000
        self.slots = 0
        self.node_id = None
        self.device = ""
        self._state = None
        self._proc = QProcess(self)
        self._proc.finished.connect(self._on_push_done)
        self._pending = False
        self._retried = False
        self._conf_timer = QTimer(self, singleShot=True, interval=500)
        self._conf_timer.timeout.connect(self._write_conf)
        self._poll = QTimer(self, interval=5000)
        self._poll.timeout.connect(self._refresh)

    # --- service ---------------------------------------------------------
    def start(self, state):
        """Install the unit and config, and (re)start the service if anything changed."""
        self._state = state
        self.slots = slots_for(len(state.bands))
        unit_changed = self._write_if_changed(UNIT_FILE, build_unit())
        conf_changed = self._write_if_changed(CONF_FILE, build_conf(state, self.slots))
        if unit_changed:
            _systemctl("daemon-reload")
        _systemctl("enable", SERVICE)
        active = _systemctl("is-active", SERVICE).stdout.strip() == "active"
        if not active or unit_changed or conf_changed:
            self._restart()
        self._refresh()
        self._poll.start()

    @staticmethod
    def _write_if_changed(path, text):
        try:
            if path.read_text() == text:
                return False
        except OSError:
            pass
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        return True

    def _restart(self):
        self.node_id = None
        r = _systemctl("restart", SERVICE)
        if r.returncode != 0:
            self.status.emit(tr("Failed to start the EQ service: {err}", err=r.stderr.strip()))

    def _write_conf(self):
        if self._state is not None:
            self._write_if_changed(CONF_FILE, build_conf(self._state, self.slots))

    # --- graph introspection -------------------------------------------
    def _refresh(self):
        try:
            objs = json.loads(subprocess.run(["pw-dump"], capture_output=True, text=True, timeout=3).stdout)
        except (OSError, ValueError, subprocess.TimeoutExpired):
            return
        nodes = {o["id"]: o for o in objs if o.get("type") == "PipeWire:Interface:Node"}

        def name_of(o):
            return o.get("info", {}).get("props", {}).get("node.name")

        self.node_id = next((i for i, o in nodes.items() if name_of(o) == NODE_IN), None)
        out_id = next((i for i, o in nodes.items() if name_of(o) == NODE_OUT), None)

        rate = None
        device = ""
        for o in objs:
            if o.get("type") != "PipeWire:Interface:Link":
                continue
            info = o.get("info", {})
            if info.get("output-node-id") == out_id and info.get("input-node-id") in nodes:
                dev = nodes[info["input-node-id"]]
                device = name_of(dev) or device
                for fmt in dev.get("info", {}).get("params", {}).get("Format", []):
                    rate = fmt.get("rate") or rate
                if rate:
                    break
        if device and device != self.device:
            self.device = device
            self.deviceChanged.emit(device)
        if not rate:
            rate = self._metadata_rate(objs)
        if rate and rate != self.rate:
            self.rate = rate
            self.rateChanged.emit(rate)
            self.push()
        state = tr("EQ running") if self.node_id is not None else tr("EQ stopped")
        self.status.emit(f"{state} · {self.rate} Hz · {tr('The EQ stays on after you close this window')}")

    @staticmethod
    def _metadata_rate(objs):
        for o in objs:
            if o.get("type") == "PipeWire:Interface:Metadata" and o.get("props", {}).get("metadata.name") == "settings":
                vals = {m.get("key"): m.get("value") for m in o.get("metadata", [])}
                for key in ("clock.force-rate", "clock.rate"):
                    try:
                        if int(vals.get(key) or 0) > 0:
                            return int(vals[key])
                    except (TypeError, ValueError):
                        pass
        return None

    # --- applying changes ------------------------------------------------
    def apply(self, state):
        self._state = state
        need = slots_for(len(state.bands))
        if need != self.slots:
            self.slots = need
            self._write_conf()
            self._restart()
            QTimer.singleShot(800, self._refresh)
            return
        self.push()
        self._conf_timer.start()

    def push(self):
        """Send the current state live; if a send is in flight, send the latest state once it finishes."""
        if self._state is None:
            return
        if self._proc.state() != QProcess.ProcessState.NotRunning:
            self._pending = True
            return
        if self.node_id is None:
            self._refresh()
            if self.node_id is None:
                return
        params = [f'"pre:Mult" {_f(preamp_mult(self._state))}']
        for i, cf in enumerate(slot_coeffs(self._state, self.slots, self.rate)):
            params += [f'"s{i + 1}:{k}" {_f(v)}' for k, v in zip(("b0", "b1", "b2", "a0", "a1", "a2"), cf)]
        self._pending = False
        self._proc.start("pw-cli", ["set-param", str(self.node_id), "Props", "{ params = [ " + " ".join(params) + " ] }"])

    def _on_push_done(self, code, _status):
        err = bytes(self._proc.readAllStandardError()).decode(errors="replace")
        out = bytes(self._proc.readAllStandardOutput()).decode(errors="replace")
        if code != 0 or "rror" in err or "rror" in out:
            # e.g. the filter-chain restarted and got a new node id
            self.node_id = None
            if not self._retried:
                self._retried = True
                self._pending = True
        else:
            self._retried = False
        if self._pending:
            self.push()
